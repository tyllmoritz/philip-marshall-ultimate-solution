import { defineConfig } from "vite";
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

/**
 * Offline support: writes sw.js next to the page. It precaches every file of the build; the cache name is a hash of
 * their contents, so it changes whenever any file does (index.html and the algorithm sets carry no hash in their names).
 * The page itself is loaded network-first, so it always matches the scripts on the server, and from the cache only
 * when offline; everything else (hashed scripts, icons, algorithm sets) comes from the cache first.
 * Install fetches with cache: "reload": through the browser's HTTP cache (GitHub Pages: max-age=600) it could
 * store an old index.html next to the new scripts, a page whose scripts are gone.
 */
function serviceWorker() {
  let outDir = "dist";
  return {
    name: "marshall-service-worker",
    apply: "build",
    configResolved(config) { outDir = resolve(config.root, config.build.outDir); },
    // after everything (the worker sub-builds included) is on disk, list what is there
    closeBundle() {
      const walk = (dir, base = "") => readdirSync(dir, { withFileTypes: true }).flatMap((d) => (d.isDirectory() ? walk(join(dir, d.name), base + d.name + "/") : [base + d.name]));
      const files = ["./", ...walk(outDir).filter((f) => f !== "sw.js" && !f.endsWith(".map"))].sort();
      const hash = createHash("sha1");
      for (const f of files.filter((x) => x !== "./")) hash.update(f + "\0").update(readFileSync(join(outDir, f))).update("\0");
      const version = hash.digest("hex").slice(0, 10);
      writeFileSync(join(outDir, "sw.js"), `// generated by vite.config.js
const CACHE = "marshall-${version}";
const PRECACHE = ${JSON.stringify(files)};

self.addEventListener("install", (event) => {
  // straight from the network: an HTTP-cached index.html could belong to the previous build
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE.map((url) => new Request(url, { cache: "reload" })))).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("marshall-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === "navigate") {
    // the page: from the server (revalidated, so it matches the scripts there), from the cache only when offline
    event.respondWith(
      fetch(req, { cache: "no-cache" }).then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put("./", copy)); }
        return res;
      }).catch(() => caches.match("./")),
    );
    return;
  }
  event.respondWith(
    caches.match(req, { ignoreVary: true }).then((hit) => {
      if (hit) return hit;
      return fetch(req).then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
        return res;
      }).catch(() => Response.error());
    }),
  );
});
`);
    },
  };
}

export default defineConfig({
  base: "./",
  worker: { format: "es" },
  build: { target: "es2022" },
  plugins: [serviceWorker()],
});
