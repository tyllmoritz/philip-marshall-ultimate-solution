import { defineConfig } from "vite";
import { createHash } from "node:crypto";
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

/**
 * Offline support: writes sw.js next to the page. It precaches every file of the build (names carry content
 * hashes, so the list - and so the cache name - changes whenever the app does) and serves from the cache first, so the app also
 * starts without a network once it has been loaded.
 */
function serviceWorker() {
  let outDir = "dist";
  return {
    name: "marshall-service-worker",
    apply: "build",
    configResolved(config) { outDir = resolve(config.root, config.build.outDir); },
    // after everything (the worker sub-builds included) is on disk, list what is there
    closeBundle() {
      const walk = (dir, base = "") => readdirSync(dir, { withFileTypes: true }).flatMap((d) => (d.isDirectory() ? walk(join(dir, d.name), base + d.name + "/") : [base + d.name]));
      const files = ["./", ...walk(outDir).filter((f) => f !== "sw.js" && !f.endsWith(".map"))].sort();
      const sizes = files.filter((f) => f !== "./").map((f) => f + statSync(join(outDir, f)).size).join("|");
      const version = createHash("sha1").update(sizes).digest("hex").slice(0, 10);
      writeFileSync(join(outDir, "sw.js"), `// generated by vite.config.js
const CACHE = "marshall-${version}";
const PRECACHE = ${JSON.stringify(files)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("marshall-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.match(req, { ignoreSearch: req.mode === "navigate", ignoreVary: true }).then((hit) => {
      if (hit) return hit;
      return fetch(req).then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
        return res;
      }).catch(() => (req.mode === "navigate" ? caches.match("./") : Response.error()));
    }),
  );
});
`);
    },
  };
}

export default defineConfig({
  base: "./",
  worker: { format: "es" },
  build: { target: "es2022" },
  plugins: [serviceWorker()],
});
